"""用户可见文案的集中定义。

为什么需要这个文件：同一句文案此前散落在多个文件里——

* "编辑草稿已更新，请刷新后重试" 出现 5 次（main.py 3 处 + edit_sessions.py 2 处）
* "人物列表已更新，请刷新后重试" 出现 4 次（main.py）
* 封面保存这一个事件有 5 种说法（"封面已生成并保存为当前任务封面，同时绑定到…" /
  "已将时间轴中的封面设为当前封面…" / "已保存为当前任务封面…"）

改一个字要改多处，必然产生不一致。新增或修改用户可见文案时请优先写在这里，再由各处引用。

原则：**结果进消息流，约束进界面**。
"这不是正式导出""未覆盖原成片"这类不变的约束属于界面事实，不要每条消息都念一遍。

写作规范
--------
新增或修改用户可见文案时请遵守以下三条，它们是「提示文案收敛」这件事的落地规则。

1. 结果进消息流，约束进界面
   消息只说发生了什么：``已生成 3 个审核样片。``
   "不是正式导出""没覆盖原成片""历史版本仍保留"属于界面事实，由结果卡徽标
   （``审核样片 · 非导出``，见 static/workspace-controller.js）和版本列表承载，
   不再逐条消息重复。

2. 人称
   对话流（``append_message`` 正文、artifact ``message``）用第一人称「我」：
      我已生成待审核时间线草案「…」。
   状态标签（``currentAction`` / ``detail``）省略主语：
      正在核定检索结果
   「Agent」只保留给专有名词：Agent 计划、Agent 计划面板、Agent 审核预览、Agent 模型、
   智能剪辑 Agent（产品名）。不要再用「Agent 已…」这种第三人称自称。

3. 标点
   消息流的完整句以「。」结尾（全项目 239 条消息已按此统一）。
   状态标签、按钮、面板标题、进行中短语不带句尾标点。
   不要在「：」后面直接接「。」。
"""
